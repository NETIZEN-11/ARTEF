#!/usr/bin/env python3
"""Create a local development configuration for the backend (no Docker required).

Writes, only if they do not already exist:
  backend/.keys/jwt_private.pem, backend/.keys/jwt_public.pem   RS256 signing keys
  backend/.env                                                  SQLite dev settings

Both paths are gitignored. Run from the repository root:
    python scripts/dev_setup.py
"""
import secrets
import sys
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa

BACKEND = Path(__file__).resolve().parent.parent / "backend"
KEYS = BACKEND / ".keys"
ENV_FILE = BACKEND / ".env"


def write_keys() -> None:
    private_path, public_path = KEYS / "jwt_private.pem", KEYS / "jwt_public.pem"
    if private_path.exists() and public_path.exists():
        print(f"keys exist: {KEYS}")
        return
    KEYS.mkdir(exist_ok=True)
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    private_path.write_bytes(
        key.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption(),
        )
    )
    public_path.write_bytes(
        key.public_key().public_bytes(
            serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo
        )
    )
    print(f"wrote RS256 keys to {KEYS}")


def write_env() -> None:
    if ENV_FILE.exists():
        print(f"{ENV_FILE} exists, leaving it unchanged")
        return
    ENV_FILE.write_text(
        "\n".join(
            [
                "# Local development settings, generated by scripts/dev_setup.py",
                "ENVIRONMENT=development",
                "DEBUG=false",
                f"SECRET_KEY={secrets.token_urlsafe(48)}",
                "DATABASE_URL=sqlite+aiosqlite:///./artef_dev.db",
                "REDIS_URL=redis://localhost:6379/0",
                "CELERY_BROKER_URL=redis://localhost:6379/1",
                "CELERY_RESULT_BACKEND=redis://localhost:6379/2",
                f"JWT_PRIVATE_KEY_PATH={(KEYS / 'jwt_private.pem').as_posix()}",
                f"JWT_PUBLIC_KEY_PATH={(KEYS / 'jwt_public.pem').as_posix()}",
                "# Run tasks inside the API process instead of a Celery worker (no Redis needed).",
                "# Leave false when Redis + `celery worker` are running (see README).",
                "CELERY_TASK_ALWAYS_EAGER=false",
                "# The demo target agents run on localhost, so allow private addresses locally.",
                "TARGET_AGENT_BLOCK_PRIVATE_IPS=false",
                "# local = deterministic judge for llm_rubric tests; 'live' calls the configured",
                "# judge LLM (set PRIMARY_JUDGE_API_KEY etc.). Matchers never call an LLM.",
                "EVAL_MODE=local",
                "",
                "# Used only by scripts/seed_demo_data.py. Random per machine; log in as 'admin'",
                "# with SEED_ADMIN_PASSWORD.",
                *[
                    f"SEED_{role}_PASSWORD={secrets.token_urlsafe(12)}"
                    for role in ("ADMIN", "SAFETY", "ML", "QA", "REVIEWER", "VIEWER")
                ],
                "SEED_EMAIL_DOMAIN=redteam.local",
                "# Demo target agents (demo/target_agent.py). The prod/staging entries are",
                "# placeholders that are never called by the demo.",
                "SEED_MOCK_AGENT_V1_URL=http://localhost:9001/chat",
                "SEED_MOCK_AGENT_V2_URL=http://localhost:9002/chat",
                "SEED_PROD_AGENT_URL=https://example.invalid/agent/chat",
                "SEED_STAGING_AGENT_URL=https://example.invalid/staging/agent/chat",
                f"SEED_AGENT_AUTH_TOKEN={secrets.token_urlsafe(24)}",
                "",
            ]
        ),
        encoding="utf-8",
    )
    print(f"wrote {ENV_FILE}")


if __name__ == "__main__":
    if not BACKEND.is_dir():
        sys.exit(f"backend directory not found at {BACKEND}")
    write_keys()
    write_env()
